/// <summary>
/// Adapter for WasmEdge.
/// Generates a Node.js-compatible shim that loads the Wasm module via the
/// WasmEdge runtime and bridges HTTP requests.
/// </summary>
type WasmEdgeAdapter() =

    interface IPlatformAdapter with

        member _.Platform = PlatformKind.WasmEdge

        member _.HandleRequest (request: HttpRequest) (_env: Env) =
            async {
                return
                    { StatusCode = 200
                      Headers = []
                      Body = None
                      ContentType = None }
            }

        member _.GenerateShim() =
            String.concat
                Environment.NewLine
                [ "// wasmedge-entry.js — auto-generated by FSharp.Wasm.Host"
                  "const { WASI } = require('wasi');"
                  "const { readFile } = require('fs/promises');"
                  "const http = require('http');"
                  ""
                  "async function main() {"
                  "  const wasi = new WASI({ version: 'preview1' });"
                  "  const wasmBytes = await readFile('./app.wasm');"
                  "  const { instance } = await WebAssembly.instantiate(wasmBytes, {"
                  "    wasi_snapshot_preview1: wasi.wasiImport,"
                  "  });"
                  "  wasi.start(instance);"
                  ""
                  "  const server = http.createServer((req, res) => {"
                  "    const chunks = [];"
                  "    req.on('data', (c) => chunks.push(c));"
                  "    req.on('end', () => {"
                  "      const body = Buffer.concat(chunks);"
                  "      const result = instance.exports.handle_request(req.method, req.url, req.headers, body);"
                  "      res.writeHead(result.status, result.headers);"
                  "      res.end(result.body);"
                  "    });"
                  "  });"
                  ""
                  "  server.listen(3000, () => console.log('WasmEdge host listening on :3000'));"
                  "}"
                  ""
                  "main();" ]
