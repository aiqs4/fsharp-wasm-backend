                [ "// fastly-entry.js — auto-generated by FSharp.Wasm.Host"
                  "import { env } from 'fastly:env';"
                  ""
                  "addEventListener('fetch', (event) => {"
                  "  event.respondWith(handleRequest(event));"
                  "});"
                  ""
                  "async function handleRequest(event) {"
                  "  const req = event.request;"
                  "  const url = new URL(req.url);"
                  "  // Forward to Wasm module"
                  "  const wasmResult = globalThis.__wasm_handle(req.method, url.pathname, req.headers, await req.arrayBuffer());"
                  "  return new Response(wasmResult.body, {"
                  "    status: wasmResult.status,"
                  "    headers: wasmResult.headers,"
                  "  });"
                  "}" ]

