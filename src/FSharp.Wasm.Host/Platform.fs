namespace FSharp.Wasm.Host

open System

/// <summary>
/// Contract for platform-specific adapters that bridge the host environment
/// to the F# Wasm request pipeline.
/// </summary>
type IPlatformAdapter =
    /// <summary>The platform this adapter targets.</summary>
    abstract member Platform: PlatformKind

    /// <summary>
    /// Handle an incoming HTTP request with access to the host environment.
    /// Adapters may override this to add platform-specific middleware (e.g.
    /// KV binding, secrets injection).
    /// </summary>
    abstract member HandleRequest: HttpRequest -> Env -> Async<HttpResponse>

    /// <summary>
    /// Generate a platform-specific entry-point shim (JavaScript glue code,
    /// manifest snippet, etc.) that wires the host to the Wasm module.
    /// </summary>
    abstract member GenerateShim: unit -> string

/// <summary>
/// Adapter for Cloudflare Workers.
/// Generates a <c>cloudflare-entry.js</c> shim that imports the Wasm module
/// and forwards fetch events to the F# request handler.
/// </summary>
type CloudflareAdapter() =

    interface IPlatformAdapter with

        member _.Platform = PlatformKind.Cloudflare

        member _.HandleRequest (request: HttpRequest) (_env: Env) =
            async {
                return
                    { StatusCode = 200
                      Headers = []
                      Body = None
                      ContentType = None }
            }

        member _.GenerateShim() =
            String.concat
                Environment.NewLine
                [ "// cloudflare-entry.js — auto-generated by FSharp.Wasm.Host"
                  "import { WASI } from '@aspect-build/wasi';"
                  "import wasmModule from './app.wasm';"
                  ""
                  "const wasi = new WASI();"
                  "const instance = new WebAssembly.Instance(wasmModule, {"
                  "  wasi_snapshot_preview1: wasi.wasiImport,"
                  "});"
                  "wasi.start(instance);"
                  ""
                  "export default {"
                  "  async fetch(request, env, ctx) {"
                  "    const url = new URL(request.url);"
                  "    const method = request.method;"
                  "    const headers = Object.fromEntries(request.headers);"
                  "    const body = request.body ? new Uint8Array(await request.arrayBuffer()) : null;"
                  "    const result = instance.exports.handle_request(method, url.pathname, headers, body);"
                  "    return new Response(result.body, {"
                  "      status: result.status,"
                  "      headers: result.headers,"
                  "    });"
                  "  },"
                  "};" ]

